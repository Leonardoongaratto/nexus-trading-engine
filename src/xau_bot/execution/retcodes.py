from xau_bot.broker.mt5_mapping import (
    RETCODE_CANCEL,
    RETCODE_CLIENT_DISABLES_AT,
    RETCODE_CONNECTION,
    RETCODE_DONE,
    RETCODE_DONE_PARTIAL,
    RETCODE_ERROR,
    RETCODE_FROZEN,
    RETCODE_INVALID,
    RETCODE_INVALID_EXPIRATION,
    RETCODE_INVALID_FILL,
    RETCODE_INVALID_PRICE,
    RETCODE_INVALID_STOPS,
    RETCODE_INVALID_VOLUME,
    RETCODE_LOCKED,
    RETCODE_MARKET_CLOSED,
    RETCODE_NO_CHANGES,
    RETCODE_NO_MONEY,
    RETCODE_ORDER_CHANGED,
    RETCODE_PLACED,
    RETCODE_PRICE_CHANGED,
    RETCODE_PRICE_OFF,
    RETCODE_REJECT,
    RETCODE_REQUOTE,
    RETCODE_SERVER_DISABLES_AT,
    RETCODE_TIMEOUT,
    RETCODE_TOO_MANY_REQUESTS,
    RETCODE_TRADE_DISABLED,
)
from xau_bot.execution.models import RetcodeAction

_SUCCESS_RETCODES: frozenset[int] = frozenset(
    {
        RETCODE_PLACED,
        RETCODE_DONE,
        RETCODE_DONE_PARTIAL,
    }
)

_RETRY_WITH_RECONCILIATION_RETCODES: frozenset[int] = frozenset(
    {
        RETCODE_REQUOTE,
        RETCODE_TIMEOUT,
        RETCODE_PRICE_CHANGED,
        RETCODE_PRICE_OFF,
        RETCODE_CONNECTION,
    }
)

_FATAL_ABORT_RETCODES: frozenset[int] = frozenset(
    {
        RETCODE_REJECT,
        RETCODE_CANCEL,
        RETCODE_ERROR,
        RETCODE_INVALID,
        RETCODE_INVALID_VOLUME,
        RETCODE_INVALID_PRICE,
        RETCODE_INVALID_STOPS,
        RETCODE_TRADE_DISABLED,
        RETCODE_MARKET_CLOSED,
        RETCODE_NO_MONEY,
        RETCODE_INVALID_EXPIRATION,
        RETCODE_ORDER_CHANGED,
        RETCODE_TOO_MANY_REQUESTS,
        RETCODE_NO_CHANGES,
        RETCODE_SERVER_DISABLES_AT,
        RETCODE_CLIENT_DISABLES_AT,
        RETCODE_LOCKED,
        RETCODE_FROZEN,
        RETCODE_INVALID_FILL,
    }
)


def classify_retcode(retcode: int) -> RetcodeAction:
    if retcode in _SUCCESS_RETCODES:
        return RetcodeAction.SUCCESS
    if retcode in _RETRY_WITH_RECONCILIATION_RETCODES:
        return RetcodeAction.RETRY_WITH_RECONCILIATION
    if retcode in _FATAL_ABORT_RETCODES:
        return RetcodeAction.FATAL_ABORT
    return RetcodeAction.FATAL_ABORT
